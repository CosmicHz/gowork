// Package shell 生成各 shell 的集成代码：只负责把目标目录切过去。
package shell

import (
	"fmt"
	"io"
	"strings"
)

// template 返回 shell 名称对应的集成代码。bash / zsh / POSIX sh 的函数体相同。
func template(shell string) (string, bool) {
	switch strings.ToLower(shell) {
	case "powershell", "pwsh":
		return initPowerShell, true
	case "sh", "bash", "zsh", "posix":
		return initSH, true
	case "fish":
		return initFish, true
	}
	return "", false
}

// Init 把 shell 集成代码写到 out。用法是 `gowork init <shell>`，
// 由用户在 shell 配置里 eval / source 这段输出。
func Init(args []string, out io.Writer) error {
	if len(args) != 1 {
		return fmt.Errorf("用法: gowork init <shell>\n可用: powershell、sh（bash / zsh / POSIX）、fish")
	}
	s, ok := template(args[0])
	if !ok {
		return fmt.Errorf("不支持的 shell：%s\n可用: powershell、sh（bash / zsh / POSIX）、fish", args[0])
	}
	fmt.Fprint(out, s)
	return nil
}

const initSH = `# 由 gowork init sh 生成；bash / zsh / POSIX sh 通用。
work() {
    local bin cwd_file rc
    bin=${GOWORK_BIN:-gowork}

    if ! command -v "$bin" >/dev/null 2>&1; then
        printf 'work: 未找到 %s，请先构建并放进 PATH，或用 GOWORK_BIN 指定\n' "$bin" >&2
        return 127
    fi

    cwd_file=$(command mktemp) || {
        printf 'work: 无法创建临时文件\n' >&2
        return 1
    }

    command "$bin" --cwd-file="$cwd_file" "$@"
    rc=$?

    if [ "$rc" -eq 0 ] && [ -s "$cwd_file" ]; then
        # 反斜杠让命令名不被别名替换（POSIX 行为），否则用户若 alias 过 cd 就会跑偏。
        \cd -- "$(command cat "$cwd_file")" || rc=$?
    fi

    command rm -f "$cwd_file"
    return "$rc"
}
`

const initFish = `# 由 gowork init fish 生成。
function work --description 'gowork：跳转项目并渲染仪表盘'
    set -l bin gowork
    if set -q GOWORK_BIN
        set bin $GOWORK_BIN
    end

    if not command -sq $bin
        echo "work: 未找到 $bin，请先构建并放进 PATH，或用 GOWORK_BIN 指定" >&2
        return 127
    end

    set -l cwd_file (command mktemp)
    if test -z "$cwd_file"
        echo 'work: 无法创建临时文件' >&2
        return 1
    end

    command $bin --cwd-file=$cwd_file $argv
    set -l rc $status

    if test $rc -eq 0; and test -s $cwd_file
        cd (command cat $cwd_file)
        or set rc $status
    end

    command rm -f $cwd_file
    return $rc
end
`

// initPowerShell 的输出必须保持纯 ASCII：PowerShell 用控制台代码页解码原生命令的
// stdout（中文 Windows 上常见 GBK/936），UTF-8 中文会吞掉换行或引号，导致
// Invoke-Expression 报假的语法错误。所以这份模板的注释与提示语一律用英文。
//
// 不用 param 块：那样会把 `--indent 5` 的 `--indent` 绑到第一个位置参数，
// 原生参数就无法透传。没有 param 块时所有实参都在 $args，脚本里只翻译
// Windows 写法的 -Project / -IndentSize / -Workspace（含 PowerShell 的无歧义缩写），
// 其余原样交给 gowork。
const initPowerShell = `# Generated by gowork init powershell.
function global:work {
    # Translate Windows-style options to native gowork options. PowerShell
    # parameter abbreviations such as -Proj / -Ind / -Work are accepted.
    # Everything else (--no-color, -n, -1, project names, ...) is passed through.
    function Resolve-GoworkName {
        param([string]$Name)

        # Single lowercase letters are native short options (-p / -i / -w / ...).
        if ($null -eq $Name -or $Name.Length -eq 0) { return $null }
        if ($Name.Length -eq 1 -and $Name -cmatch '^[picnwh]$') { return $null }

        $found = $null
        foreach ($candidate in @('Project', 'IndentSize', 'Workspace')) {
            if ($candidate.StartsWith($Name, [System.StringComparison]::OrdinalIgnoreCase)) {
                if ($null -ne $found) { return $null }
                $found = $candidate
            }
        }
        return $found
    }

    function ConvertTo-GoworkArgs {
        param([string[]]$InputArgs)

        $items = @($InputArgs)
        $out = @()
        for ($i = 0; $i -lt $items.Count; $i++) {
            $arg = [string]$items[$i]

            if ($arg.StartsWith('-')) {
                $dashCount = 1
                if ($arg.StartsWith('--')) { $dashCount = 2 }

                $body = $arg.Substring($dashCount)
                $eq = $body.IndexOf('=')
                if ($eq -ge 0) {
                    $name = $body.Substring(0, $eq)
                    $suffix = $body.Substring($eq)
                }
                else {
                    $name = $body
                    $suffix = ''
                }

                $windowsName = Resolve-GoworkName $name
                if ($null -ne $windowsName) {
                    $nativeName = $windowsName.ToLowerInvariant()
                    if ($windowsName -eq 'IndentSize') { $nativeName = 'indent' }

                    if ($eq -ge 0) {
                        $out += "--$nativeName$suffix"
                        continue
                    }

                    $out += "--$nativeName"
                    if ($i + 1 -lt $items.Count) {
                        $i++
                        $out += [string]$items[$i]
                    }
                    continue
                }
            }

            $out += $arg
        }
        return $out
    }

    $exe = if ($env:GOWORK_BIN) { $env:GOWORK_BIN } else { 'gowork' }
    $found = if ($env:GOWORK_BIN) {
        Microsoft.PowerShell.Management\Test-Path -LiteralPath $exe -PathType Leaf
    }
    else {
        Microsoft.PowerShell.Core\Get-Command $exe -ErrorAction SilentlyContinue
    }
    if (-not $found) {
        Microsoft.PowerShell.Utility\Write-Error "gowork not found: $exe. Build it into PATH or set GOWORK_BIN."
        $global:LASTEXITCODE = 127
        return
    }

    $cwdFile = [System.IO.Path]::GetTempFileName()
    try {
        $exeArgs = @("--cwd-file=$cwdFile") + @(ConvertTo-GoworkArgs $args)

        # Start-Process joins arguments as-is, so each one is quoted here.
        $argumentLine = ($exeArgs | Microsoft.PowerShell.Core\ForEach-Object { '"' + $_.Replace('"', '\"') + '"' }) -join ' '

        # Start-Process lets gowork.exe own the console directly, bypassing the
        # PowerShell output pipeline; otherwise $PSStyle.OutputRendering strips ANSI.
        $proc = Microsoft.PowerShell.Management\Start-Process -FilePath $exe -ArgumentList $argumentLine -NoNewWindow -Wait -PassThru
        $global:LASTEXITCODE = $proc.ExitCode

        if ($proc.ExitCode -eq 0) {
            $target = Microsoft.PowerShell.Management\Get-Content -LiteralPath $cwdFile -Raw -ErrorAction SilentlyContinue
            if ($target) {
                Microsoft.PowerShell.Management\Set-Location -LiteralPath $target.Trim()
            }
        }
    }
    finally {
        Microsoft.PowerShell.Management\Remove-Item -LiteralPath $cwdFile -Force -ErrorAction SilentlyContinue
    }
}
`
